import { join } from "node:path"
import { RunDir, type ShellCaller, type Supply } from "oc-secure-kit"
import { classifyAz, findAzCalls, SSH_KEY, vmAlias, type Account, type VmSummary } from "./model.js"
import { publicKeyOf, TOKEN_PATTERNS, type AzureService } from "./service.js"

/** Shell commands reference this to reach VMs: ssh -F "$AZURE_SSH_CONFIG" <alias>. */
export const SSH_CONFIG_VAR = "AZURE_SSH_CONFIG"
const SSH_REFERENCE = new RegExp(`\\$\\{?${SSH_CONFIG_VAR}\\b`)
const ALIAS = /\baz-[a-z0-9][a-z0-9-]*[a-z0-9]\b/g

const order = ["read", "write", "spend", "delete", "admin"]

export function renderVmConfig(entries: readonly { account: string; alias: string; vm: VmSummary }[], options: { keysDir: string; knownHosts: string }): string {
  const lines = ["# Generated by oc-azure for one command. Use: ssh -F \"$AZURE_SSH_CONFIG\" <vm alias>", ""]
  for (const { account, alias, vm } of entries) {
    if (!vm.publicIp) continue
    lines.push(
      `Host ${alias}`, `  HostName ${vm.publicIp}`, `  User ${vm.adminUser ?? "azureuser"}`, `  IdentityFile ${join(options.keysDir, account)}`,
      "  IdentitiesOnly yes", "  IdentityAgent none", `  HostKeyAlias azure-${vm.name.toLowerCase()}-${vm.resourceGroup.toLowerCase()}`,
      `  UserKnownHostsFile ${options.knownHosts}`, "  StrictHostKeyChecking accept-new", "  BatchMode yes", "  ServerAliveInterval 30", "  ConnectTimeout 20", "",
    )
  }
  return lines.join("\n")
}

/** Decides what a native shell command gets: az credentials for one account, and/or VM SSH config. */
export async function prepareCommand(service: AzureService, command: string, caller: ShellCaller): Promise<Supply | undefined> {
  const { calls, account: named } = findAzCalls(command)
  const wantsSsh = SSH_REFERENCE.test(command)
  if ((!calls.length && !wantsSsh) || named === "none") return undefined
  const accounts = await service.store.list()
  if (!accounts.length) return undefined
  const notes: string[] = []
  const env: Record<string, string> = {}
  let secrets = false
  const check = (capability: string, account: Account, metadata: Record<string, unknown>) => service.bridge.check({
    sessionID: caller.sessionID, ...(caller.agent && { agent: caller.agent }), ...(caller.source && { source: caller.source }),
    capability, entities: [account.id], metadata: { ...metadata, command: command.length > 400 ? `${command.slice(0, 400)}…` : command },
  })
  const runDir = await RunDir.create(join(service.dir, "run"))
  let onDone: (() => Promise<void>) | undefined

  if (calls.length) {
    let account: Account | undefined
    try { account = await service.pick(named) } catch (error) { notes.push((error as Error).message) }
    env.AZURE_CORE_COLLECT_TELEMETRY = "no"
    env.PATH = `${service.tools.shimDir}:${process.env.PATH ?? ""}`
    if (!(await service.tools.ready())) {
      notes.push("The Azure CLI is still being installed for oc-azure (one time, a few minutes); try again shortly.")
      void service.tools.ensure().catch(() => {})
    }
    // Always isolate: without permission the command runs signed out instead of falling back to another login.
    env.AZURE_CONFIG_DIR = runDir.file("azure")
    if (account) {
      const needed = [...new Set(calls.map(classifyAz))].sort((a, b) => order.indexOf(a.split("-").at(-1)!) - order.indexOf(b.split("-").at(-1)!))
      let allowed = true
      for (const capability of needed) {
        try { await check(capability, account, { action: `az ${calls.map(call => call.words.join(" ")).join("; az ")}`.slice(0, 300), account: account.id }) }
        catch (error) { allowed = false; notes.push(`az for ${account.id} was not allowed (${capability}): ${(error as Error).message.slice(0, 200)}. The command ran signed out.`); break }
      }
      if (allowed) {
        if (!(await service.signedIn(account))) notes.push(`${account.id} is not signed in: call azure_signin account=${account.id}.`)
        const { configDir, save } = await service.materialize(account, runDir)
        env.AZURE_CONFIG_DIR = configDir
        secrets = true
        onDone = save
      }
    }
  }

  if (wantsSsh) {
    const aliases = [...new Set(command.match(ALIAS) ?? [])]
    const entries: { account: string; alias: string; vm: VmSummary }[] = []
    for (const account of accounts) {
      const prefix = vmAlias(account.id, { name: "x" }).slice(0, -1)
      const wanted = aliases.filter(alias => alias.startsWith(prefix))
      if (!wanted.length) continue
      try { await check("ssh", account, { vms: wanted.join(", ") }) } catch (error) { notes.push(`SSH to ${account.id}'s VMs was not allowed: ${(error as Error).message.slice(0, 200)}`); continue }
      let running = (await service.store.discovery(account.id))?.running ?? []
      if (wanted.some(alias => !running.some(vm => vmAlias(account.id, vm) === alias))) running = (await service.rediscover(account)).running ?? []
      for (const alias of wanted) {
        const vm = running.find(item => vmAlias(account.id, item) === alias)
        if (!vm) { notes.push(`${alias}: no running VM with that alias in ${account.id} (azure_list shows them; stopped VMs must be started).`); continue }
        if (vm.os === "windows") { notes.push(`${alias} runs Windows; use az vm run-command invoke instead of SSH.`); continue }
        if (!vm.publicIp) { notes.push(`${alias} has no public IP (private ${vm.privateIp ?? "?"}); reach it through Azure Bastion or a jump host in its network, or run commands with az vm run-command invoke.`); continue }
        entries.push({ account: account.id, alias, vm })
      }
      const key = await service.vault.get(account.id, SSH_KEY)
      if (key && entries.some(entry => entry.account === account.id)) { await runDir.write(join("keys", account.id), key.endsWith("\n") ? key : `${key}\n`); secrets = true }
      else if (!key && entries.some(entry => entry.account === account.id)) notes.push(`${account.id} has no plugin SSH key yet: azure_ssh_setup account=${account.id} vm=<name> adds it to a VM.`)
    }
    if (!aliases.length) notes.push(`No VM alias is named in this command; $${SSH_CONFIG_VAR} is empty. azure_list shows the aliases (az-<account>-<vm>).`)
    env[SSH_CONFIG_VAR] = await runDir.write("ssh_config", renderVmConfig(entries, { keysDir: runDir.file("keys"), knownHosts: join(service.dir, "known_hosts") }))
  }
  return { env, notes, secrets, runDir, mask: TOKEN_PATTERNS, ...(onDone && { onDone }) }
}

/** Tip after a failed command that used VM aliases without the plugin's config. */
export function sshTip(command: string, result: unknown): string | undefined {
  if (!/\baz-[a-z0-9-]+/.test(command) || SSH_REFERENCE.test(command) || !/\bssh|scp|rsync\b/.test(command)) return undefined
  return /Could not resolve hostname|ssh: connect/.test(JSON.stringify(result ?? "")) ? `VM aliases only work with the plugin's config: ssh -F "$${SSH_CONFIG_VAR}" <alias>, or rsync -e "ssh -F '$${SSH_CONFIG_VAR}'" …` : undefined
}

